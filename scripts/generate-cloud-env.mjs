import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
let localValues = {};
try {
  const content = await readFile(resolve(root, ".env"), "utf8");
  localValues = Object.fromEntries(
    content
      .split(/\r?\n/)
      .map((line) => line.trim())
      .filter((line) => line && !line.startsWith("#"))
      .map((line) => {
        const separator = line.indexOf("=");
        return [line.slice(0, separator), line.slice(separator + 1)];
      }),
  );
} catch {
  // The development environment is available without a local .env file.
}

const values = { ...localValues, ...process.env };
const environments = {
  develop: values.DEVELOPMENT_CLOUDBASE_ENV_ID || "cloud1-d1g8z3590d3768cbb",
  trial: values.TRIAL_CLOUDBASE_ENV_ID || "",
  release: values.PRODUCTION_CLOUDBASE_ENV_ID || "",
};
if (process.argv.includes("--for-upload")) {
  for (const version of ["trial", "release"]) {
    if (!environments[version] || environments[version].startsWith("replace-")) {
      throw new Error(`禁止上传：${version} 版本未配置云环境，上传包必须同时支持体验版和正式版`);
    }
  }
}
const output = `// Generated by scripts/generate-cloud-env.mjs. Do not edit.\nexport const CLOUD_ENV_IDS = ${JSON.stringify(environments, null, 2)} as const;\n`;
await writeFile(resolve(root, "apps/miniprogram/config/cloud-env.generated.ts"), output);
